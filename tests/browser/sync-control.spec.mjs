import {test,expect} from '@playwright/test';
test('settings consolidate language, appearance, ChatGPT and live sync on desktop and touch screens',async({page,browser})=>{
  let requests=0;
  await page.route('**/api/library',route=>{requests++;return route.fulfill({json:{records:[]}});});
  await page.goto('/');
  const gear=page.getByRole('button',{name:'Settings',exact:true});
  await expect(page.locator('.header [data-locale],.header nav,.header .sync-control')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'My recipes',exact:true})).toHaveCount(0);
  await gear.focus();await page.keyboard.press('Enter');
  await expect(page.locator('.sync-label')).toHaveText('Recipes synced');
  await expect(page.locator('[data-locale]')).toBeVisible();
  await expect(page.getByRole('button',{name:'Theme',exact:true})).toBeVisible();
  const before=requests;await page.getByRole('button',{name:'Sync now',exact:true}).click();await expect.poll(()=>requests).toBeGreaterThan(before);
  await page.getByRole('button',{name:'ChatGPT',exact:true}).click();await expect(page.locator('#chatgpt-prompt')).toBeVisible();await expect(page.locator('[data-locale]')).toHaveCount(0);
  await page.getByRole('button',{name:'Back to settings',exact:true}).click();
  await page.screenshot({path:'artifacts/settings-desktop.png'});
  await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).not.toBeVisible();await expect(gear).toBeFocused();
  const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true});
  await context.route('**/api/library',route=>route.fulfill({status:503,json:{error:'Offline'}}));
  const phone=await context.newPage();await phone.goto('/');
  await phone.getByRole('button',{name:'Settings',exact:true}).tap();
  await expect(phone.getByRole('button',{name:'Retry sync',exact:true})).toBeVisible();
  expect(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await phone.screenshot({path:'artifacts/settings-phone.png'});
  await phone.getByRole('button',{name:'Close',exact:true}).tap();await expect(phone.getByRole('dialog')).not.toBeVisible();
  await context.close();
});
